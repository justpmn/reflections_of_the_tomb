#pragma once
#include "Renderer.h"
#include <map>
#include <string>
#include <cctype>

// Small embedded bitmap typeface: readable menus without external font files.
class GameUI {
public:
    explicit GameUI(Renderer& renderer) : r(renderer) {}
    void panel(float x,float y,float w,float h) { r.drawRectangle(x,y,w,h,.035f,.045f,.075f); }
    void text(const std::string& value,float x,float y,float size=1,float red=.9f,float green=.84f,float blue=.66f) {
        static const std::map<char,std::string> glyphs = {
            {'A',"01110100011000111111100011000110001"},{'B',"11110100011000111110100011000111110"},
            {'C',"01111100001000010000100001000001111"},{'D',"11110100011000110001100011000111110"},
            {'E',"11111100001000011110100001000011111"},{'F',"11111100001000011110100001000010000"},
            {'G',"01111100001000010111100011000101111"},{'H',"10001100011000111111100011000110001"},
            {'I',"11111001000010000100001000010011111"},{'J',"00111000100001000010100101001001100"},
            {'K',"10001100101010011000101001001010001"},{'L',"10000100001000010000100001000011111"},
            {'M',"10001110111010110101100011000110001"},{'N',"10001110011010110011100011000110001"},
            {'O',"01110100011000110001100011000101110"},{'P',"11110100011000111110100001000010000"},
            {'Q',"01110100011000110001101011001001101"},{'R',"11110100011000111110101001001010001"},
            {'S',"01111100001000001110000010000111110"},{'T',"11111001000010000100001000010000100"},
            {'U',"10001100011000110001100011000101110"},{'V',"10001100011000110001100010101000100"},
            {'W',"10001100011000110101101011010101010"},{'X',"10001100010101000100010101000110001"},
            {'Y',"10001100010101000100001000010000100"},{'Z',"11111000010001000100010001000011111"},
            {'0',"01110100011001110101110011000101110"},{'1',"00100011000010000100001000010001110"},
            {'2',"01110100010000100010001000100011111"},{'3',"11110000010000101110000010000111110"},
            {'4',"00010001100101010010111110001000010"},{'5',"11111100001000011110000010000111110"},
            {'6',"01110100001000011110100011000101110"},{'7',"11111000010001000100010000100001000"},
            {'8',"01110100011000101110100011000101110"},{'9',"01110100011000101111000010000101110"},
            {'-',"00000000000000011111000000000000000"},{'/',"00001000100001000100010000100010000"},
            {':',"00000001000010000000001000010000000"},{'.',"00000000000000000000000000011000110"}
        };
        const float sx=.0020f*size, sy=.0036f*size;
        for (unsigned char c:value) {
            auto it=glyphs.find(static_cast<char>(std::toupper(c)));
            if (it!=glyphs.end()) for (int row=0;row<7;++row) for(int col=0;col<5;++col)
                if (it->second[row*5+col]=='1') r.drawRectangle(x+col*sx,y-row*sy,sx*.88f,sy*.88f,red,green,blue);
            x+=sx*6;
        }
    }
    bool button(const std::string& label,float y,double mx,double my,bool click) {
        const bool hover=mx>-.62 && mx<.62 && my>y-.035 && my<y+.065;
        r.drawRectangle(-.62f,y-.035f,1.24f,.10f,hover?.23f:.11f,hover?.21f:.13f,hover?.15f:.18f);
        text(label,-.53f,y+.025f,1.65f);
        return hover && click;
    }
private:
    Renderer& r;
};
